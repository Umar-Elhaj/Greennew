#!/usr/bin/env python3
"""
GREEN — build frontend/js/translations.js from frontend/i18n/*.json.

Each source file is {"en": {...}, "fr": {...}} for ONE top-level namespace
named after the file (common.json → keys "common.*"). The output is loaded
synchronously in <head> (no flash of untranslated text, works offline).

Usage:  python scripts/build_i18n.py           # write
        python scripts/build_i18n.py --check   # exit 1 if out of date
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "frontend" / "i18n"
OUT = ROOT / "frontend" / "js" / "translations.js"
HEADER = "// GENERATED by scripts/build_i18n.py from frontend/i18n/*.json: do not edit by hand.\n"


def merged() -> dict:
    out = {"en": {}, "fr": {}}
    for f in sorted(SRC.glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        for lang in out:
            out[lang][f.stem] = data.get(lang, {})
    return out


def render() -> str:
    body = json.dumps(merged(), ensure_ascii=False, indent=1, sort_keys=False)
    return f"{HEADER}window.GREEN_I18N_DICT = {body};\n"


def load_generated(path: Path = OUT) -> dict:
    """Parse translations.js back into a dict (used by check_i18n.py and tests)."""
    text = path.read_text(encoding="utf-8")
    start, end = text.index("{"), text.rindex("}")
    return json.loads(text[start:end + 1])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    content = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print("translations.js is out of date: run python scripts/build_i18n.py")
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
