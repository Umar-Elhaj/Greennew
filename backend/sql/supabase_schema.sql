-- ============================================================
-- GREEN App — Schéma PostgreSQL (Supabase)
-- RÉFÉRENCE de l'état final du schéma. La voie normale est Alembic :
--   cd backend && alembic upgrade head
-- Si ce fichier est exécuté à la main (Supabase > SQL Editor) sur une base
-- vide, marquez ensuite la base comme à jour : alembic stamp head
--
-- Reflète exactement backend/models.py (SQLAlchemy) ; vérifié par
-- tests/test_migrations.py::test_reference_sql_matches_models.
-- Les images ne sont PAS stockées ici : seul leur chemin relatif
-- (ex. "2026/10/3f2a….jpg") est conservé dans disease_analyses.image_path.
--
-- Les dates sont en "timestamp" sans fuseau, toujours en UTC
-- (le backend utilise datetime.utcnow()).
-- ============================================================

begin;

-- ------------------------------------------------------------
-- USERS — Comptes de la plateforme
-- ------------------------------------------------------------
create table if not exists public.users (
    id              integer generated by default as identity primary key,
    first_name      varchar(100) not null,
    last_name       varchar(100) not null,
    phone           varchar(20)  not null unique,
    email           varchar(255) unique,
    password_hash   varchar(255) not null,
    company_name    varchar(255),
    region          varchar(100),
    avatar_url      varchar(500),
    is_active       boolean not null default true,
    -- Green Data : accord pour réutiliser les images dans le dataset
    dataset_consent boolean not null default false,
    -- Conserver la position GPS trouvée dans les métadonnées des photos
    location_consent boolean not null default false,
    -- farmer | agronomist (vérifie les analyses) | partner (GREEN Data) | admin
    role            varchar(20) not null default 'farmer'
                    constraint users_role_check check (role in ('farmer', 'agronomist', 'partner', 'admin')),
    created_at      timestamp not null default (now() at time zone 'utc'),
    updated_at      timestamp not null default (now() at time zone 'utc')
);

-- ------------------------------------------------------------
-- PARCELS — Parcelles agricoles
-- ------------------------------------------------------------
create table if not exists public.parcels (
    id          integer generated by default as identity primary key,
    user_id     integer not null references public.users(id) on delete cascade,
    name        varchar(255) not null,
    crop_type   varchar(100),
    area_ha     double precision,
    region      varchar(100),
    description text,
    geometry    jsonb,                -- Polygone GeoJSON (Leaflet)
    latitude    double precision,
    longitude   double precision,
    is_active   boolean not null default true,
    created_at  timestamp not null default (now() at time zone 'utc'),
    updated_at  timestamp not null default (now() at time zone 'utc')
);

create index if not exists ix_parcels_user_id on public.parcels(user_id);

-- ------------------------------------------------------------
-- DISEASE_ANALYSES — Chaque analyse d'image (= une entrée Green Data)
-- ------------------------------------------------------------
create table if not exists public.disease_analyses (
    id               integer generated by default as identity primary key,
    user_id          integer not null references public.users(id)   on delete cascade,
    parcel_id        integer          references public.parcels(id) on delete cascade,

    -- Entrée
    source           varchar(50) default 'camera',   -- camera | upload | drone
    image_path       varchar(500),                   -- chemin relatif dans MEDIA_DIR
    image_sha256     char(64),                       -- détection des doublons
    image_bytes      integer,                        -- taille du JPEG stocké
    image_width      integer,
    image_height     integer,

    -- Sortie du modèle
    detected_disease varchar(255),
    disease_name     varchar(255),
    confidence       double precision
                     constraint disease_analyses_confidence_check check (confidence between 0 and 1),
    severity         varchar(50),
    plant_type       varchar(100),
    predictions      jsonb,                          -- top-3 [{class, confidence}]
    model_version    varchar(100),

    -- GPS
    latitude         double precision,
    longitude        double precision,

    fiche_terrain    jsonb,
    notes            text,

    -- Green Data : validation humaine + consentement
    consent_dataset  boolean not null default false,
    verified_label   varchar(255),                   -- classe corrigée par un agronome
    verified_by      integer references public.users(id) on delete set null,
    verified_at      timestamp,

    created_at       timestamp not null default (now() at time zone 'utc')
);

create index if not exists ix_disease_analyses_user_id    on public.disease_analyses(user_id);
create index if not exists ix_disease_analyses_parcel_id  on public.disease_analyses(parcel_id);
create index if not exists ix_disease_analyses_created_at on public.disease_analyses(created_at);
create index if not exists ix_disease_analyses_sha256     on public.disease_analyses(image_sha256);
-- Export du dataset : images consenties, avec image
create index if not exists ix_disease_analyses_dataset
    on public.disease_analyses(plant_type, detected_disease)
    where consent_dataset and image_path is not null;

-- ------------------------------------------------------------
-- CHAT_SESSIONS — Conversations GreenBot
-- ------------------------------------------------------------
create table if not exists public.chat_sessions (
    id         integer generated by default as identity primary key,
    user_id    integer not null references public.users(id) on delete cascade,
    title      varchar(255),
    created_at timestamp not null default (now() at time zone 'utc'),
    updated_at timestamp not null default (now() at time zone 'utc')
);

create index if not exists ix_chat_sessions_user_id on public.chat_sessions(user_id);

-- ------------------------------------------------------------
-- CHAT_MESSAGES — Messages d'une conversation
-- ------------------------------------------------------------
create table if not exists public.chat_messages (
    id          integer generated by default as identity primary key,
    session_id  integer not null references public.chat_sessions(id) on delete cascade,
    role        varchar(20) not null
                constraint chat_messages_role_check check (role in ('user', 'assistant')),
    content     text not null,
    -- Supprimer une analyse ne doit pas casser l'historique du chat
    analysis_id integer references public.disease_analyses(id) on delete set null,
    created_at  timestamp not null default (now() at time zone 'utc')
);

create index if not exists ix_chat_messages_session_id on public.chat_messages(session_id);

-- ------------------------------------------------------------
-- SÉCURITÉ — Row Level Security
-- Le backend se connecte en direct (rôle postgres, qui ignore la RLS).
-- Activer la RLS SANS politique bloque l'API publique de Supabase
-- (clé anon) : sans ça, n'importe qui pourrait lire users.password_hash.
-- ------------------------------------------------------------
alter table public.users            enable row level security;
alter table public.parcels          enable row level security;
alter table public.disease_analyses enable row level security;
alter table public.chat_sessions    enable row level security;
alter table public.chat_messages    enable row level security;

commit;
