"""
Alembic migrations ⇄ models parity.

- SQLite: `upgrade head` on an empty database produces exactly the models.
- PostgreSQL (TEST_POSTGRES_URL, disposable server): same check, plus the
  production path — schema created by sql/supabase_schema.sql at commit
  36d4768, `stamp 0001_baseline`, `upgrade head` — must also match.
"""

import os
import tempfile
import uuid

import pytest
from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from sqlalchemy import create_engine, text

import models  # noqa: F401
from database import Base
from schema_check import ALEMBIC_INI, head_revision

BASELINE_SQL = os.path.join(os.path.dirname(__file__), "fixtures", "supabase_schema_36d4768.sql")


def _alembic(url: str) -> Config:
    cfg = Config(ALEMBIC_INI)
    cfg.attributes["url"] = url
    cfg.attributes["skip_logging"] = True
    return cfg


def _diff(url: str) -> list:
    eng = create_engine(url)
    with eng.connect() as conn:
        ctx = MigrationContext.configure(conn, opts={"compare_type": True})
        diff = compare_metadata(ctx, Base.metadata)
        rev = ctx.get_current_revision()
    eng.dispose()
    assert rev == head_revision()
    return diff


def test_sqlite_upgrade_head_matches_models():
    url = "sqlite:///" + os.path.join(tempfile.mkdtemp(), "mig.db")
    command.upgrade(_alembic(url), "head")
    assert _diff(url) == []


def test_offline_sql_generation():
    """`alembic upgrade head --sql` (shown at CP2) must render for PostgreSQL."""
    import contextlib
    import io

    cfg = _alembic("postgresql://u:p@localhost:5432/db?sslmode=require")
    out = io.StringIO()
    cfg.output_buffer = out
    with contextlib.redirect_stdout(out):
        command.upgrade(cfg, "head", sql=True)
    sql = out.getvalue()
    assert "CREATE TABLE users" in sql and "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "DROP " not in sql.upper().replace("DROP NOT NULL", "")


@pytest.fixture
def pg_url():
    base = os.environ.get("TEST_POSTGRES_URL")
    if not base:
        pytest.skip("TEST_POSTGRES_URL not set")
    admin = create_engine(base, isolation_level="AUTOCOMMIT")
    name = "green_mig_" + uuid.uuid4().hex[:8]
    with admin.connect() as c:
        c.execute(text(f'create database "{name}"'))
    url = base.rsplit("/", 1)[0] + "/" + name
    yield url
    with admin.connect() as c:
        c.execute(text(f'drop database "{name}" with (force)'))
    admin.dispose()


@pytest.mark.postgres
def test_postgres_upgrade_head_matches_models(pg_url):
    command.upgrade(_alembic(pg_url), "head")
    assert _diff(pg_url) == []


@pytest.mark.postgres
def test_postgres_existing_supabase_schema_stamp_then_upgrade(pg_url):
    eng = create_engine(pg_url)
    with eng.begin() as c:
        c.exec_driver_sql(open(BASELINE_SQL, encoding="utf-8").read())
    eng.dispose()
    cfg = _alembic(pg_url)
    command.stamp(cfg, "0001_baseline")
    command.upgrade(cfg, "head")
    assert _diff(pg_url) == []


@pytest.mark.postgres
def test_reference_sql_matches_models(pg_url):
    """sql/supabase_schema.sql (for the Supabase SQL editor) must stay in sync."""
