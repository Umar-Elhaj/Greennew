@pytest.mark.mysql
def test_mysql_reference_sql_matches_models(mysql_url):
    """sql/mysql_schema.sql (phpMyAdmin import) must stay in sync, alembic_version at head."""
    eng = create_engine(mysql_url)
    with eng.begin() as c:
        for statement in _sql_statements(MYSQL_SQL):
            c.exec_driver_sql(statement)
    eng.dispose()
    assert _diff(mysql_url) == []


