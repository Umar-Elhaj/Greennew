"""
Alembic migrations ⇄ models parity.

- SQLite: `upgrade head` on an empty database produces exactly the models.
- MySQL/MariaDB (TEST_MYSQL_URL, disposable server — production on
  o2switch): `upgrade head` and sql/mysql_schema.sql both match the models.
- PostgreSQL (TEST_POSTGRES_URL, disposable server — former Supabase
  database): same check, plus the path of the old production database —
  schema created by sql/supabase_schema.sql at commit 36d4768,
  `stamp 0001_baseline`, `upgrade head` — must also match.
"""

import os
import tempfile
import uuid

import pytest
from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from sqlalchemy import create_engine, text

import models  # noqa: F401
from database import Base
from db_url import normalize_database_url
from schema_check import ALEMBIC_INI, head_revision

BASELINE_SQL = os.path.join(os.path.dirname(__file__), "fixtures", "supabase_schema_36d4768.sql")
MYSQL_SQL = os.path.join(os.path.dirname(__file__), "..", "sql", "mysql_schema.sql")


def _alembic(url: str) -> Config:
    cfg = Config(ALEMBIC_INI)
    cfg.attributes["url"] = url
    cfg.attributes["skip_logging"] = True
    return cfg


def _diff(url: str) -> list:
    eng = create_engine(url)
    with eng.connect() as conn:
        ctx = MigrationContext.configure(conn, opts={"compare_type": True})
        diff = compare_metadata(ctx, Base.metadata)
        rev = ctx.get_current_revision()
    eng.dispose()
    assert rev == head_revision()
    return diff


def test_sqlite_upgrade_head_matches_models():
    url = "sqlite:///" + os.path.join(tempfile.mkdtemp(), "mig.db")
    command.upgrade(_alembic(url), "head")
    assert _diff(url) == []


def test_offline_sql_generation():
    """`alembic upgrade head --sql` (shown at CP2) must render for PostgreSQL."""
    import contextlib
    import io

    cfg = _alembic("postgresql://u:p@localhost:5432/db?sslmode=require")
    out = io.StringIO()
    cfg.output_buffer = out
    with contextlib.redirect_stdout(out):
        command.upgrade(cfg, "head", sql=True)
    sql = out.getvalue()
    assert "CREATE TABLE users" in sql and "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "DROP " not in sql.upper().replace("DROP NOT NULL", "")


def _offline_sql(url: str) -> str:
    import contextlib
    import io

    cfg = _alembic(url)
    out = io.StringIO()
    cfg.output_buffer = out
    with contextlib.redirect_stdout(out):
        command.upgrade(cfg, "head", sql=True)
    return out.getvalue()


def test_offline_sql_generation_mysql():
    """Production (o2switch) DDL: DOUBLE, DATETIME(6), MEDIUMTEXT, InnoDB/utf8mb4, nothing dropped."""
    sql = _offline_sql(normalize_database_url("mysql://u:p@localhost:3306/db"))
    assert "CREATE TABLE users" in sql and "AUTO_INCREMENT" in sql
    assert "DATETIME(6)" in sql and "DOUBLE" in sql and "MEDIUMTEXT" in sql
    assert " FLOAT" not in sql and "TEXT," not in sql.replace("MEDIUMTEXT,", "")
    assert sql.count("ENGINE=InnoDB") == sql.count("CREATE TABLE") - 1  # all but alembic_version
    assert sql.count("CHARSET=utf8mb4") == sql.count("ENGINE=InnoDB")
    assert "DROP " not in sql.upper()


def _sql_statements(path: str) -> list:
    """Statements of a .sql file without its -- comments (no ';' inside strings)."""
    lines = [ln.split("--", 1)[0] for ln in open(path, encoding="utf-8")]
    return [s.strip() for s in "\n".join(lines).split(";") if s.strip()]


